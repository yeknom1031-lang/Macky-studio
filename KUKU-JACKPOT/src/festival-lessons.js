export const STAGE_DESIGNS=entries.map((e,i)=>Object.freeze({id:i+1,title:e[0],instruction:e[1],suffix:e[2],success:e[3],action:e[4],cues:e[5],progress:e[6]}));
export const stageDesign=id=>STAGE_DESIGNS[id-1]||STAGE_DESIGNS[0];
export function lessonHint(q,{recalling=false}={}){
 const l=q.lesson||{};
 if(q.gameId===5)return `${q.a}ずつ ジャンプ！ ${l.from??q.a*(q.b-1)}の次は？`;
 if(q.gameId===2)return `${q.a}こずつ × ${q.b}皿。ぜんぶで？`;
 if(q.gameId===7)return `${q.a}こずつ × ${q.b}組。何こ入りの箱？`;
 if(q.gameId===9)return `1両に${q.a}人 × ${q.b}両。ぜんぶで？`;
 if(q.gameId===10)return `1杯に${q.a}こ × ${q.b}杯。果物は何こ？`;
 if(q.gameId===11&&l.retry)return 'リバウンド！ さっきの九九、覚えてる？';
 if(q.gameId===12)return l.showHint&&!recalling?'この九九を覚えよう。すぐ答えてもOK！':'消えた答えを 呼びもどそう！';
 if(q.gameId===13&&l.role==='second')return `こんどは逆！ ${q.b} × ${q.a}と同じ答え`; 
 if(q.gameId===14)return `${l.known?.answer??q.a*(q.b-1)}から、もう${q.a}！`;
 return stageDesign(q.gameId).instruction;
}
export function answerDisplay(gameId,control){
 const label=gameId===18?control.label.split(' ')[0]:control.label;
 return {label,suffix:stageDesign(gameId).suffix};
}
export function practicePrompt(q,controls){
 const expected=[4,21].includes(q.gameId)?Number(q.truth):q.answer;
 const c=controls.find(c=>c.value===expected);
 const {label,suffix}=answerDisplay(q.gameId,c||controls[0]);
 return {expected,title:`「${label}」をタップ！`,detail:[4,21].includes(q.gameId)?`この式は${q.truth?'正しいよ':'ちがうよ'}。下のボタンで${q.gameId===4?'見きわめよう':'答えよう'}。`:`下の「${label}${suffix}」を1回だけ押してみよう。`};
}
